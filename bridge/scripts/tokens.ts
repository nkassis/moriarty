// Generates src/mycroft/tokens.css and src/mycroft/tokens.ts from docs/design/mycroft/tokens.json.
// `node scripts/tokens.ts` writes both; `--check` exits 1 if the committed files differ.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export interface Theme {
    id: string;
    name: string;
}

export interface ColorToken {
    name: string;
    value: string | Record<string, string>;
    usage: string;
}

export interface TypeStyle {
    name: string;
    fontSize: string;
    lineHeight: string;
    fontWeight: number;
    letterSpacing?: string;
    sample: string;
    usage: string;
}

export interface TypeGroup {
    name: string;
    family: string;
    styles: TypeStyle[];
}

export interface ScalarToken {
    name: string;
    value: string;
    usage: string;
}

export interface Tokens {
    color: { themes: Theme[]; tokens: ColorToken[] };
    type: { families: Record<string, string>; groups: TypeGroup[] };
    spacing: { tokens: ScalarToken[] };
    radius: { tokens: ScalarToken[] };
    layout: { tokens: ScalarToken[] };
}

/** One colour as written in a theme block: a literal or a reference to another token. */
export interface ThemeValue {
    css: string;
    resolved: string;
}

const ALIAS: RegExp = /^\{([a-z0-9-]+)\}$/;
const BASE_THEME: string = "standard";
const HEADER: string =
    "Mycroft tokens. Generated by bridge/scripts/tokens.ts from docs/design/mycroft/tokens.json; do not edit.";

function rawValue(token: ColorToken, theme: string): string {
    if (typeof token.value === "string") return token.value;
    const own: string | undefined = token.value[theme];
    if (own !== undefined) return own;
    const base: string | undefined = token.value[BASE_THEME];
    if (base === undefined) throw new Error(`colour ${token.name} has no ${BASE_THEME} value`);
    return base;
}

/**
 * Every colour for one theme, fully resolved. A theme that omits a token inherits the standard
 * value, and an alias is re-declared in every theme so it follows that theme's target even when
 * themes nest.
 */
export function resolveTheme(tokens: Tokens, theme: string): Map<string, ThemeValue> {
    const byName: Map<string, ColorToken> = new Map(tokens.color.tokens.map((t) => [t.name, t]));
    const out: Map<string, ThemeValue> = new Map();
    const resolveOne = (name: string, seen: readonly string[]): string => {
        if (seen.includes(name)) throw new Error(`alias cycle: ${[...seen, name].join(" -> ")}`);
        const token: ColorToken | undefined = byName.get(name);
        if (token === undefined) throw new Error(`unknown colour alias {${name}}`);
        const raw: string = rawValue(token, theme);
        const alias: RegExpExecArray | null = ALIAS.exec(raw);
        return alias?.[1] === undefined ? raw : resolveOne(alias[1], [...seen, name]);
    };
    for (const token of tokens.color.tokens) {
        const raw: string = rawValue(token, theme);
        const alias: RegExpExecArray | null = ALIAS.exec(raw);
        out.set(token.name, {
            css: alias?.[1] === undefined ? raw : `var(--${alias[1]})`,
            resolved: resolveOne(token.name, []),
        });
    }
    return out;
}

function familyVar(family: string): string {
    return `var(--font-${family})`;
}

function allStyles(tokens: Tokens): { group: TypeGroup; style: TypeStyle }[] {
    return tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ group, style })));
}

export function buildCss(tokens: Tokens): string {
    const lines: string[] = [`/* ${HEADER} */`];
    for (const theme of tokens.color.themes) {
        const selector: string =
            theme.id === BASE_THEME
                ? `:root,\n[data-theme="${theme.id}"]`
                : `[data-theme="${theme.id}"]`;
        lines.push(`${selector} {`);
        for (const [name, value] of resolveTheme(tokens, theme.id)) {
            lines.push(`  --${name}: ${value.css};`);
        }
        lines.push("}");
    }
    lines.push(":root {");
    for (const group of [tokens.spacing, tokens.radius, tokens.layout]) {
        for (const token of group.tokens) lines.push(`  --${token.name}: ${token.value};`);
    }
    for (const [family, stack] of Object.entries(tokens.type.families)) {
        lines.push(`  --font-${family}: ${stack};`);
    }
    for (const { group, style } of allStyles(tokens)) {
        const n: string = style.name;
        lines.push(`  --type-${n}-family: ${familyVar(group.family)};`);
        lines.push(`  --type-${n}-size: ${style.fontSize};`);
        lines.push(`  --type-${n}-line: ${style.lineHeight};`);
        lines.push(`  --type-${n}-weight: ${String(style.fontWeight)};`);
        lines.push(`  --type-${n}-tracking: ${style.letterSpacing ?? "normal"};`);
    }
    lines.push("}");
    for (const { style } of allStyles(tokens)) {
        const n: string = style.name;
        lines.push(
            `.type-${n} { font-family: var(--type-${n}-family); font-size: var(--type-${n}-size); ` +
                `line-height: var(--type-${n}-line); font-weight: var(--type-${n}-weight); ` +
                `letter-spacing: var(--type-${n}-tracking); }`,
        );
    }
    return lines.join("\n") + "\n";
}

function union(names: readonly string[]): string {
    return names.map((n) => JSON.stringify(n)).join(" | ");
}

function record(entries: readonly (readonly [string, string])[], indent: string): string {
    return entries.map(([k, v]) => `${indent}${JSON.stringify(k)}: ${v},`).join("\n");
}

export function buildTs(tokens: Tokens): string {
    const themes: Theme[] = tokens.color.themes;
    const colorNames: string[] = tokens.color.tokens.map((t) => t.name);
    const resolved: Map<string, Map<string, ThemeValue>> = new Map(
        themes.map((t) => [t.id, resolveTheme(tokens, t.id)]),
    );
    const scalar = (typeName: string, constName: string, list: ScalarToken[]): string[] => [
        `export type ${typeName} = ${union(list.map((t) => t.name))};`,
        `export const ${constName}: Readonly<Record<${typeName}, string>> = {`,
        record(
            list.map((t) => [t.name, JSON.stringify(t.value)] as const),
            "    ",
        ),
        "};",
        "",
    ];
    const styles: { group: TypeGroup; style: TypeStyle }[] = allStyles(tokens);
    return [
        `// ${HEADER}`,
        "",
        `export type ThemeId = ${union(themes.map((t) => t.id))};`,
        `export const THEMES: readonly { readonly id: ThemeId; readonly name: string }[] = [`,
        ...themes.map(
            (t) => `    { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)} },`,
        ),
        "];",
        "",
        `export type ColorToken = ${union(colorNames)};`,
        "/** Resolved colour per theme (aliases followed, missing themes filled from standard). */",
        "export const COLORS: Readonly<Record<ColorToken, Readonly<Record<ThemeId, string>>>> = {",
        ...colorNames.map((name) => {
            const perTheme: string = themes
                .map(
                    (t) =>
                        `${JSON.stringify(t.id)}: ${JSON.stringify(resolved.get(t.id)?.get(name)?.resolved)}`,
                )
                .join(", ");
            return `    ${JSON.stringify(name)}: { ${perTheme} },`;
        }),
        "};",
        "",
        ...scalar("SpaceToken", "SPACING", tokens.spacing.tokens),
        ...scalar("RadiusToken", "RADIUS", tokens.radius.tokens),
        ...scalar("LayoutToken", "LAYOUT", tokens.layout.tokens),
        `export type FontFamily = ${union(Object.keys(tokens.type.families))};`,
        "export const FONT_FAMILIES: Readonly<Record<FontFamily, string>> = {",
        record(
            Object.entries(tokens.type.families).map(([k, v]) => [k, JSON.stringify(v)] as const),
            "    ",
        ),
        "};",
        "",
        `export type TypeStyleName = ${union(styles.map((s) => s.style.name))};`,
        "export interface TypeStyle {",
        "    readonly family: FontFamily;",
        "    readonly fontSize: string;",
        "    readonly lineHeight: string;",
        "    readonly fontWeight: number;",
        "    readonly letterSpacing: string;",
        "}",
        "export const TYPE_STYLES: Readonly<Record<TypeStyleName, TypeStyle>> = {",
        ...styles.map(
            ({ group, style }) =>
                `    ${JSON.stringify(style.name)}: { family: ${JSON.stringify(group.family)}, ` +
                `fontSize: ${JSON.stringify(style.fontSize)}, lineHeight: ${JSON.stringify(style.lineHeight)}, ` +
                `fontWeight: ${String(style.fontWeight)}, letterSpacing: ${JSON.stringify(style.letterSpacing ?? "normal")} },`,
        ),
        "};",
        "",
        "/** `var(--name)` for any token, for the rare inline custom property. */",
        "export function cssVar(name: ColorToken | SpaceToken | RadiusToken | LayoutToken): string {",
        "    return `var(--${name})`;",
        "}",
        "",
    ].join("\n");
}

function main(argv: readonly string[]): number {
    const here: string = dirname(fileURLToPath(import.meta.url));
    const source: string = resolve(here, "../../docs/design/mycroft/tokens.json");
    const outDir: string = resolve(here, "../src/mycroft");
    const tokens: Tokens = JSON.parse(readFileSync(source, "utf8")) as Tokens;
    const outputs: [string, string][] = [
        [resolve(outDir, "tokens.css"), buildCss(tokens)],
        [resolve(outDir, "tokens.ts"), buildTs(tokens)],
    ];
    if (argv.includes("--check")) {
        const stale: string[] = outputs
            .filter(([path, text]) => {
                try {
                    return readFileSync(path, "utf8") !== text;
                } catch {
                    return true;
                }
            })
            .map(([path]) => path);
        for (const path of stale) console.error(`stale: ${path} (run pnpm gen:tokens)`);
        return stale.length === 0 ? 0 : 1;
    }
    mkdirSync(outDir, { recursive: true });
    for (const [path, text] of outputs) writeFileSync(path, text);
    return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    process.exitCode = main(process.argv.slice(2));
}
