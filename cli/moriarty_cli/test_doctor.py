from pathlib import Path

import pytest

from moriarty_cli import doctor
from moriarty_cli.paths import PROFILES_DIR
from moriarty_cli.profile import load_profile
from ship.contract.enums import DriveMode

DEMO = load_profile(PROFILES_DIR / "demo.json")
EVAL = load_profile(PROFILES_DIR / "eval.json")


def fake_capture(answers: dict[str, tuple[int, str]]) -> object:
    def capture(cmd: list[str], timeout: float = 15.0) -> tuple[int, str]:
        return answers.get(" ".join(cmd[:2]), (127, ""))

    return capture


def test_python_check_needs_3_14() -> None:
    assert doctor.python_check((3, 14, 0)).ok
    assert not doctor.python_check((3, 13, 9)).ok


def test_uv_check(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(doctor, "capture", fake_capture({"uv --version": (0, "uv 0.13.5")}))
    assert doctor.uv_check() == doctor.Check("uv", True, "0.13.5")
    monkeypatch.setattr(doctor, "capture", fake_capture({}))
    assert not doctor.uv_check().ok


def test_docker_check_reports_engine_and_compose(monkeypatch: pytest.MonkeyPatch) -> None:
    answers = {"docker info": (0, "29.2.1"), "docker compose": (0, "5.0.2")}
    monkeypatch.setattr(doctor, "capture", fake_capture(answers))
    assert doctor.docker_check().detail == "engine 29.2.1, compose 5.0.2"


def test_docker_check_tells_a_stopped_daemon_from_a_missing_binary(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(doctor, "capture", fake_capture({"docker info": (1, "")}))
    assert doctor.docker_check().detail == "daemon not reachable"
    monkeypatch.setattr(doctor, "capture", fake_capture({}))
    assert doctor.docker_check().detail == "not found"


def test_ollama_check_reports_version_and_required_models(ollama_url: str) -> None:
    check = doctor.ollama_check(ollama_url, ["gpt-oss:20b"])
    assert check.ok
    assert check.detail == f"0.0.0-test at {ollama_url}, gpt-oss:20b"


def test_ollama_check_fails_on_a_missing_model_with_the_pull_command(ollama_url: str) -> None:
    check = doctor.ollama_check(ollama_url, ["qwen3:14b"])
    assert not check.ok
    assert check.fix == "ollama pull qwen3:14b"


def test_ollama_check_fails_when_nothing_answers() -> None:
    assert not doctor.ollama_check("http://127.0.0.1:1", []).ok


def test_local_models_are_the_routes_without_a_key() -> None:
    assert doctor.local_models(EVAL) == ["gpt-oss:20b"]
    assert doctor.local_models(DEMO) == []
    assert doctor.local_models(None) == []


def test_env_file_check(tmp_path: Path) -> None:
    assert not doctor.env_file_check(tmp_path / ".env").ok
    (tmp_path / ".env").write_text("")
    assert doctor.env_file_check(tmp_path / ".env").ok


@pytest.fixture
def env_files(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    example = tmp_path / ".env.example"
    example.write_text("ANTHROPIC_API_KEY=your-key-here\n")
    return tmp_path / ".env", example


def test_provider_key_is_skipped_for_local_drive(env_files: tuple[Path, Path]) -> None:
    assert doctor.provider_key_check(DEMO, DriveMode.LOCAL, *env_files) is None


def test_provider_key_fails_when_unset_or_the_placeholder(env_files: tuple[Path, Path]) -> None:
    env, example = env_files
    check = doctor.provider_key_check(DEMO, DriveMode.REMOTE, env, example)
    assert check is not None and not check.ok and check.detail == "ANTHROPIC_API_KEY not set"
    env.write_text("ANTHROPIC_API_KEY=your-key-here\n")
    check = doctor.provider_key_check(DEMO, DriveMode.REMOTE, env, example)
    assert check is not None and not check.ok


def test_provider_key_passes_from_the_env_file_or_environment(
    env_files: tuple[Path, Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    env, example = env_files
    env.write_text("ANTHROPIC_API_KEY=sk-test\n")
    check = doctor.provider_key_check(DEMO, DriveMode.REMOTE, env, example)
    assert check is not None and check.ok
    env.unlink()
    monkeypatch.setenv("ANTHROPIC_API_KEY", "sk-test")
    check = doctor.provider_key_check(DEMO, DriveMode.REMOTE, env, example)
    assert check is not None and check.ok


def test_remote_drive_with_no_key_env_in_the_profile_fails(env_files: tuple[Path, Path]) -> None:
    check = doctor.provider_key_check(EVAL, DriveMode.REMOTE, *env_files)
    assert check is not None and not check.ok


def test_hooks_check_needs_both_pre_commit_hooks(tmp_path: Path) -> None:
    assert not doctor.hooks_check(None).ok
    (tmp_path / "pre-commit").write_text("# File generated by pre-commit\n")
    check = doctor.hooks_check(tmp_path)
    assert not check.ok and check.detail == "pre-push not installed"
    assert check.fix == doctor.HOOK_FIX
    (tmp_path / "pre-push").write_text("#!/bin/sh\necho not pre-commit's\n")
    assert not doctor.hooks_check(tmp_path).ok
    (tmp_path / "pre-push").write_text("# File generated by pre-commit\n")
    assert doctor.hooks_check(tmp_path).ok


def test_trufflehog_check(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(doctor.shutil, "which", lambda name: None)
    assert not doctor.trufflehog_check().ok
    monkeypatch.setattr(doctor.shutil, "which", lambda name: f"/usr/bin/{name}")
    assert doctor.trufflehog_check().ok


def test_git_email_check_never_prints_the_address(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(doctor, "capture", fake_capture({"git -C": (0, "a@b.example")}))
    check = doctor.git_email_check(Path("."))
    assert check.ok and "a@b" not in check.line()
    monkeypatch.setattr(doctor, "capture", fake_capture({"git -C": (1, "")}))
    assert not doctor.git_email_check(Path(".")).ok


def test_profile_check_reports_validation_errors(tmp_path: Path) -> None:
    bad = tmp_path / "bad.json"
    bad.write_text("{}")
    check, profile = doctor.profile_check(bad)
    assert not check.ok and profile is None
    check, profile = doctor.profile_check(PROFILES_DIR / "eval.json")
    assert check.ok and profile == EVAL


def test_every_failure_line_carries_its_fix() -> None:
    line = doctor.Check("uv", False, "not found", "install uv").line()
    assert line.startswith("FAIL") and line.endswith("-> install uv")
    assert "->" not in doctor.Check("uv", True, "0.13.5", "install uv").line()
